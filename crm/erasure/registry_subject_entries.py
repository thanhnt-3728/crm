"""Registry entries for her person records: Lead, Deal, the Deal's contact row, Contact, Address, links

The first four are resolved together (each can lead to the others) before anything else runs.
"""

from crm.erasure.registry_model import (
	CLEAR,
	DELETE_ROWS,
	DROP_HER_LINKS,
	MARKER,
	NAME_MARKER,
	PERSON,
	SCRUB,
	SUBJECTS,
	UNLINK,
	Backref,
	ChildLink,
	Emails,
	Entry,
	Link,
	Phones,
)

_CONTACT_POINTS = (("email", CLEAR), ("mobile_no", CLEAR), ("phone", CLEAR))

SUBJECT_ENTRIES = (
	Entry(
		doctype="CRM Lead",
		kind=PERSON,
		found_by="The request's source; email, mobile_no or phone is hers; the lead of one of her deals",
		action=SCRUB,
		finders=(Emails(("email",)), Phones(("mobile_no", "phone")), Backref("CRM Deal", "lead")),
		fields=(
			("salutation", CLEAR),
			("first_name", NAME_MARKER),
			("middle_name", CLEAR),
			("last_name", CLEAR),
			("lead_name", NAME_MARKER),
			*_CONTACT_POINTS,
			("gender", CLEAR),
			("job_title", CLEAR),
			("image", CLEAR),
			("linkedin", CLEAR),
			("twitter", CLEAR),
			("facebook", CLEAR),
			("facebook_lead_id", CLEAR),
			("lost_notes", MARKER),
		),
		keep=(
			"status",
			"source",
			"lead_owner",
			"territory",
			"organization",
			"annual_revenue",
			"total",
			"net_total",
			"converted",
			"lost_reason",
		),
	),
	Entry(
		doctype="CRM Deal",
		kind=PERSON,
		found_by=(
			"Deals converted from her lead; deal contact is her Contact; email, mobile_no or phone is hers. "
			"A deal where she is only one of the contacts is not hers: only her contact row is scrubbed"
		),
		action=SCRUB,
		finders=(
			Link("lead", "CRM Lead"),
			Link("contact", "Contact"),
			Emails(("email",)),
			Phones(("mobile_no", "phone")),
		),
		fields=(
			("salutation", CLEAR),
			("first_name", NAME_MARKER),
			("last_name", CLEAR),
			("lead_name", NAME_MARKER),
			*_CONTACT_POINTS,
			("gender", CLEAR),
			("job_title", CLEAR),
			("lost_notes", MARKER),
		),
		keep=(
			"status",
			"deal_value",
			"expected_deal_value",
			"probability",
			"expected_closure_date",
			"closed_date",
			"deal_owner",
			"organization",
			"lost_reason",
		),
	),
	Entry(
		doctype="CRM Contacts",
		kind=PERSON,
		found_by="Contact rows of any deal whose contact is her Contact, or whose email or phone is hers",
		action=SCRUB,
		finders=(Link("contact", "Contact"), Emails(("email",)), Phones(("mobile_no", "phone"))),
		fields=(("full_name", NAME_MARKER), *_CONTACT_POINTS, ("gender", CLEAR)),
		keep=("contact", "is_primary"),
	),
	Entry(
		doctype="Contact",
		kind=PERSON,
		found_by="The request's source; email_id, phone or mobile_no is hers; any Contact Email or Contact Phone row is hers",
		action=SCRUB,
		finders=(
			Emails(("email_id",)),
			Phones(("phone", "mobile_no")),
			Emails(("email_id",), child_doctype="Contact Email"),
			Phones(("phone",), child_doctype="Contact Phone"),
		),
		fields=(
			("salutation", CLEAR),
			("first_name", NAME_MARKER),
			("middle_name", CLEAR),
			("last_name", CLEAR),
			("full_name", NAME_MARKER),
			("email_id", CLEAR),
			("phone", CLEAR),
			("mobile_no", CLEAR),
			("image", CLEAR),
			("gender", CLEAR),
			("designation", CLEAR),
			("department", CLEAR),
			("user", CLEAR),
			("google_contacts_id", CLEAR),
			("email_ids", DELETE_ROWS),
			("phone_nos", DELETE_ROWS),
		),
		keep=("links", "company_name", "status"),
	),
	Entry(
		doctype="Address",
		kind=PERSON,
		found_by="Addresses whose links point at her Lead, Deal or Contact. Scrubbed when linked only to her, else her link is removed",
		action=SCRUB,
		shared_action=UNLINK,
		finders=(ChildLink("Dynamic Link", SUBJECTS),),
		fields=(
			("address_title", NAME_MARKER),
			("address_line1", MARKER),
			("address_line2", CLEAR),
			("city", MARKER),
			("county", CLEAR),
			("state", CLEAR),
			("pincode", CLEAR),
			("email_id", CLEAR),
			("phone", CLEAR),
			("fax", CLEAR),
			("links", DROP_HER_LINKS),
		),
		keep=("address_type", "country"),
	),
	Entry(
		doctype="Dynamic Link",
		kind=PERSON,
		found_by="Link rows of any record whose link_name is her Lead, Deal or Contact (link_title caches her name)",
		action=SCRUB,
		match_rows=False,
		fields=(("link_title", NAME_MARKER),),
		keep=("link_doctype", "link_name"),
	),
	Entry(
		doctype="Communication Link",
		kind=PERSON,
		found_by="Timeline links of any Communication whose link_name is her Lead, Deal or Contact",
		action=SCRUB,
		match_rows=False,
		fields=(("link_title", NAME_MARKER),),
		keep=("link_doctype", "link_name"),
	),
)
